export type IconName = keyof typeof ICONS;

/** Convierte la grilla en rectángulos de 1x1 para el SVG. */
export function iconRects(name: IconName): Array<[number, number]> {
	const out: Array<[number, number]> = [];
	ICONS[name].forEach((row, y) => {
		[...row].forEach((cell, x) => {
			if (cell === '#') out.push([x, y]);
		});
	});
	return out;
}
